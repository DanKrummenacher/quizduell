import { chromium } from '@playwright/test';
import { readFileSync } from 'node:fs';
const [, , out, tag, w, h] = process.argv;
const password = readFileSync('../backend/.env', 'utf8').match(/^ADMIN_PASSWORD=(.*)$/m)[1].trim();
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: Number(w), height: Number(h) } });
const shot = (n) => page.screenshot({ path: `${out}/${tag}-${n}.png` });
await page.goto('http://localhost:4200/');
await page.locator('h1.main-title').waitFor({ timeout: 60000 });
await shot('1-start');
await page.goto('http://localhost:4200/admin/login');
await page.getByText('Admin-Bereich').waitFor();
await shot('2-login');
await page.locator('css-input-text input').fill(password);
await page.locator('css-button', { hasText: 'Anmelden' }).click();
await page.getByText('Übersicht').first().waitFor();
await page.waitForTimeout(800);
await shot('3-dashboard');
await page.getByRole('link', { name: 'Fragen' }).click();
await page.locator('.item').first().waitFor();
await shot('4-questions');
await page.getByRole('link', { name: 'Einstellungen' }).click();
await page.getByText('Fragen pro Duell').waitFor();
await page.waitForTimeout(500);
await shot('5-settings');
await page.getByRole('link', { name: 'Fragen' }).click();
await page.locator('css-button', { hasText: 'Neue Frage' }).click();
await page.getByText('Neue Frage', { exact: true }).last().waitFor();
await page.waitForTimeout(600);
await shot('6-editor');
await browser.close();
